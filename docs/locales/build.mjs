#!/usr/bin/env node
// Renders the 41 localized README pages and docs/LANGUAGES.md from
// catalog.json, so translated text lives in one place and pages never drift
// from it. `--check` exits 1 when a page differs from what the catalog
// renders, without writing anything.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const catalog = JSON.parse(await readFile(path.join(here, "catalog.json"), "utf8"));
const KEYS = ["tagline", "stopsHeading", "stopsBody", "tryHeading", "tryBody", "installHeading", "installNext", "docsLine", "status"];
const RTL = new Set(["ar", "he"]);
const GUIDE = "../../packages/bw-core/docs/getting-started";

const STOPS = `\`\`\`text
agent  runs npm test                  → passes
agent  edits src/sum.ts               → breaks it
agent  "Done. Tests pass."
bw     ✗ Stop blocked. test: last result was for an older tree; files changed since then.

agent  git push origin main           → times out after the push landed
agent  git push origin main           (retry)
bw     ✗ Denied. git-push: the same action already succeeded at this commit.
\`\`\``;

const TRY = `\`\`\`bash
git clone --depth 1 https://github.com/stephen-taipei/better-workflows ~/.better-workflows
node ~/.better-workflows/packages/bw-core/examples/stale-green/demo.mjs
\`\`\``;

const INSTALL = `\`\`\`bash
claude plugin marketplace add ~/.better-workflows/packages/bw-core
claude plugin install better-workflows-core@better-workflows --scope local
node ~/.better-workflows/packages/bw-core/bin/bw.mjs init
\`\`\``;

function page(locale) {
  const t = catalog.text[locale.code];
  const missing = KEYS.filter((key) => typeof t?.[key] !== "string" || !t[key]);
  if (missing.length) throw new Error(`catalog.json: ${locale.code} is missing ${missing.join(", ")}`);
  const languages = catalog.locales
    .map((other) => (other.code === locale.code ? `**${other.name}**` : `[${other.name}](${other.code}.md)`))
    .join(" · ");
  // Full-width punctuation already separates sentences in CJK text.
  const status = t.machine ? `${t.status}${/[。！？]$/.test(t.status) ? "" : " "}${t.machine}` : t.status;
  const body = [
    `# Better Workflows`,
    ``,
    `**${t.tagline}**`,
    ``,
    languages,
    ``,
    `## ${t.stopsHeading}`,
    ``,
    STOPS,
    ``,
    t.stopsBody,
    ``,
    `## ${t.tryHeading}`,
    ``,
    t.tryBody,
    ``,
    TRY,
    ``,
    `## ${t.installHeading}`,
    ``,
    INSTALL,
    ``,
    t.installNext,
    ``,
    `${t.docsLine} [English](${GUIDE}.md) · [繁體中文（台灣）](${GUIDE}.zh-TW.md)`,
    ``,
    `> ${status}`,
  ].join("\n");
  const generated = `<!-- Generated by docs/locales/build.mjs from catalog.json. Edit the catalog, not this file. -->\n`;
  return RTL.has(locale.code) ? `${generated}<div dir="rtl">\n\n${body}\n\n</div>\n` : `${generated}${body}\n`;
}

function languagesIndex() {
  const rows = catalog.locales.map((l) => `| \`${l.code}\` | ${l.name} | [README](locales/${l.code}.md) |`);
  return [
    `<!-- Generated by docs/locales/build.mjs from catalog.json. Edit the catalog, not this file. -->`,
    `# Better Workflows language index`,
    ``,
    `Each locale has a short V6 README. English and Traditional Chinese (Taiwan) are written and reviewed by hand; the other locales are machine-translated from the English text, and the English README is authoritative. Commands and identifiers stay in English.`,
    ``,
    `| Locale | Native label | Page |`,
    `| --- | --- | --- |`,
    ...rows,
    ``,
  ].join("\n");
}

const outputs = new Map(catalog.locales.map((l) => [path.join(here, `${l.code}.md`), page(l)]));
outputs.set(path.join(here, "..", "LANGUAGES.md"), languagesIndex());

const check = process.argv.includes("--check");
let stale = 0;
for (const [file, text] of outputs) {
  const current = await readFile(file, "utf8").catch(() => null);
  if (current === text) continue;
  if (check) {
    process.stderr.write(`out of date: ${path.relative(process.cwd(), file)}\n`);
    stale += 1;
  } else {
    await writeFile(file, text);
  }
}
if (check && stale) {
  process.stderr.write(`Run: node docs/locales/build.mjs\n`);
  process.exit(1);
}
process.stdout.write(`${check ? "checked" : "wrote"} ${outputs.size} files\n`);
